class EvalCase(Base):
    """An HR-written test question with the expected outcome. "Run checks" scores the assistant."""

    __tablename__ = "eval_cases"
    id: Mapped[int] = mapped_column(primary_key=True)
    tenant_id: Mapped[int] = mapped_column(ForeignKey("tenants.id"), index=True)
    question: Mapped[str] = mapped_column(String(500))
    expect_route: Mapped[str] = mapped_column(String(20))  # faq | leave | policy | no_answer | sensitive
    expect_policy_title: Mapped[str] = mapped_column(String(200), default="")  # for route=policy
    expect_ref: Mapped[str] = mapped_column(String(30), default="")  # optional clause ref, e.g. "4.2"
    must_include: Mapped[str] = mapped_column(String(200), default="")  # optional phrase in the answer
    # Which employee profile to ask as (audience filters).
    as_location: Mapped[str] = mapped_column(String(100), default="")
    as_grade: Mapped[str] = mapped_column(String(50), default="")
    as_employment_type: Mapped[str] = mapped_column(String(50), default="")
    last_passed: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    last_detail: Mapped[str] = mapped_column(String(300), default="")
    last_run_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    created_by: Mapped[int] = mapped_column(ForeignKey("admin_users.id"))
